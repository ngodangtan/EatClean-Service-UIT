const MAX_RETRIES = 2;
const DEFAULT_TEMPLATE_DAYS = 7;
const DAILY_TEMPLATE_DAYS = 1; // purpose=daily_health_based generates a single day
const CONCURRENCY_LIMIT = 3;
// Allows 2 regeneration attempts per meal (validate → regen → validate → regen → validate)
const MAX_MEAL_REGEN_ATTEMPTS = 2;

const MEDICAL_DISCLAIMER = 'This meal plan is generated by AI and is not a substitute for professional medical or dietary advice. Consult your healthcare provider before making dietary changes related to your health conditions.';

/**
 * Extract disease keys from a HealthProfile.diseases entry array, filtered to
 * those the disease engine actually supports. Unsupported diseases (e.g. obesity,
 * anemia) are stored on the profile for the user's records but ignored by the
 * macro adjuster and ingredient filters.
 *
 * @param {Array<{key: string}>} diseaseEntries
 * @returns {string[]}
 */
function extractSupportedDiseaseKeys(diseaseEntries) {
  if (!Array.isArray(diseaseEntries)) return [];
  return diseaseEntries
    .map(d => d?.key)
    .filter(k => typeof k === 'string' && isSupportedDisease(k));
}

// Generate meal plan using per-meal AI generation with backend nutrition
export async function generateMealPlan(req, res) {
  try {
    const userId = req.user?.id;
    if (!userId) return res.status(401).json({ message: 'Unauthorized' });

    // Request body has already been Joi-validated by the route middleware,
    // so the field shapes here are trustworthy. The remaining checks are
    // cross-field rules that need the user's health profile.
    const { purpose, weightGoal, desiredWeight, durationWeeks, healthSnapshot } = req.body;

    // Fetch user's health profile
    const healthProfile = await HealthProfile.findOne({ userId });
    if (!healthProfile) {
      return res.status(404).json({ message: 'Health profile not found. Please complete your health profile first.' });
    }

    // Validate required fields for nutrition calculation
    const missingFields = ['gender', 'age', 'currentWeight', 'height'].filter(f => healthProfile[f] == null);
    if (missingFields.length > 0) {
      return res.status(400).json({
        message: `Health profile is missing required fields: ${missingFields.join(', ')}.`
      });
    }

    // All disease keys present on the profile (supported + unsupported).
    // The engine still ignores unsupported ones, but the request-level
    // contraindication check below uses the full set on purpose: e.g.
    // "obesity" should block weight-gain even though the macro engine
    // doesn't model it.
    const allDiseaseKeys = Array.isArray(healthProfile.diseases)
      ? healthProfile.diseases.map(d => d?.key).filter(k => typeof k === 'string')
      : [];

    // Block generation when any disease catalog limit condition is met.
    const limitCheck = checkDiseaseGenerationLimits(healthProfile.diseases);
    if (limitCheck.blocked) {
      return res.status(400).json({
        message: limitCheck.message,
        reason: limitCheck.reason,
        disease: limitCheck.disease
      });
    }

    // ── Purpose-specific request validation ──────────────────────────────
    let goalOverride;
    let tdeeOverride;
    let templateDays = DEFAULT_TEMPLATE_DAYS;
    let requestedWeeks;

    if (purpose === 'daily_health_based') {
      // Generate a single day. Apple Watch snapshot (if any) drives TDEE.
      templateDays = DAILY_TEMPLATE_DAYS;
      requestedWeeks = 1;
      tdeeOverride = tdeeFromHealthSnapshot(healthSnapshot) ?? undefined;
    } else if (purpose === 'weight_management') {
      const { blocked, conflicts } = checkWeightGoalContraindications(weightGoal, allDiseaseKeys);
      if (blocked) {
        return res.status(400).json({
          message: `Weight goal "${weightGoal}" is medically contraindicated by your recorded conditions.`,
          reason: 'weight_goal_contraindication',
          conflicts
        });
      }
      goalOverride = mapWeightGoalToEngineGoal(weightGoal);
      requestedWeeks = durationWeeks;
    } else if (purpose === 'disease_based') {
      if (allDiseaseKeys.length === 0) {
        return res.status(400).json({
          message: 'purpose=disease_based requires at least one disease on the health profile.'
        });
      }
      // Force a maintenance/improvement profile regardless of profile goal.
      goalOverride = 'improve-health';
      requestedWeeks = durationWeeks;
    }

    // Step 1: Calculate base deterministic nutrition values (no disease adjustments)
    let nutritionPlan = generateNutritionPlan(healthProfile, { goalOverride, tdeeOverride });
    logger.info('Base nutrition plan calculated:', {
      purpose,
      bmr: nutritionPlan.bmr,
      tdee: nutritionPlan.tdee,
      calorieTarget: nutritionPlan.calorieTarget,
      macros: nutritionPlan.macros
    });

    // Step 2: Apply disease-based macro adjustments if diseases present.
    // healthProfile.diseases is an array of objects ({ key, indicators, ... }).
    // The disease engine and ingredient filters expect a flat string[] of keys,
    // and only the catalog-supported subset is meaningful to them.
    const diseases = extractSupportedDiseaseKeys(healthProfile.diseases);
    const hasDiseases = diseases.length > 0;
    let unsupportedDiseases;

    if (hasDiseases) {
      // Pass a profile shim with diseases as string[] for engine compatibility.
      nutritionPlan = applyDiseaseAdjustments(
        nutritionPlan,
        { ...healthProfile.toObject?.() ?? healthProfile, diseases }
      );
      unsupportedDiseases = nutritionPlan.unsupportedDiseases;
      logger.info('Disease-adjusted macros:', nutritionPlan.macros);
    }

    // Step 3: Calculate plan duration. desiredWeight is request-scoped now;
    // disease_based and daily_health_based ignore it entirely via requestedWeeks.
    const duration = calculatePlanDuration({
      goal: nutritionPlan.goal,
      currentWeight: healthProfile.currentWeight,
      desiredWeight,
      requestedWeeks
    });
    logger.info('Plan duration:', duration);

    // Step 4: Get ingredient lists for prompt
    const forbiddenIngredients = getForbiddenIngredients(diseases);
    const limitedIngredients = getLimitedIngredients(diseases);
    const preferredIngredients = getPreferredIngredients(diseases);

    // Step 4b: RAG — retrieve grounding context per unique mealType
    const uniqueMealTypes = [...new Set(nutritionPlan.mealDistribution.map(d => d.mealType))];
    const effectiveDiseases = diseases;
    let ragContextByMealType = {};

    try {
      // Fetch disease guidelines once (same for all mealTypes) + all meal retrievals in parallel
      const [guidelines, ...mealResultsByType] = await Promise.all([
        retrieveDiseaseGuidelines(effectiveDiseases),
        ...uniqueMealTypes.map(mealType =>
          retrieveRelevantMeals({
            mealType,
            goal: nutritionPlan.goal,
            diseases: effectiveDiseases,
            cuisine: healthProfile.cuisinePreference?.[0] ?? null
          })
        )
      ]);

      for (let i = 0; i < uniqueMealTypes.length; i++) {
        ragContextByMealType[uniqueMealTypes[i]] = buildMealContext(mealResultsByType[i], guidelines);
      }
      logger.info('RAG context retrieved for meal types:', Object.keys(ragContextByMealType));
    } catch (ragErr) {
      logger.warn('RAG retrieval failed — continuing without context:', ragErr.message);
      ragContextByMealType = {};
    }

    // Shared call budget across all retries (dynamic based on meals per day)
    const mealsPerDay = nutritionPlan.mealDistribution.length;
    const aiCallBudget = Math.min(60, templateDays * mealsPerDay * 2 + 10);
    const callBudget = { remaining: aiCallBudget };

    // Step 5: Retry loop — generate template (7 days, or 1 day for daily_health_based),
    // then replicate across weeks.
    let assembledPlan = null;
    let lastErrors = null;

    for (let attempt = 0; attempt <= MAX_RETRIES; attempt++) {
      if (callBudget.remaining <= 0) {
        lastErrors = ['Global AI call budget exhausted'];
        break;
      }

      if (attempt > 0) {
        logger.info(`Plan assembly retry ${attempt + 1}/${MAX_RETRIES + 1}...`);
      }

      try {
        // Build all meal generation tasks (templateDays x mealsPerDay)
        const mealTasks = [];
        const mealMeta = []; // track dayIndex + dist for assembly

        for (let dayIndex = 0; dayIndex < templateDays; dayIndex++) {
          for (const dist of nutritionPlan.mealDistribution) {
            mealMeta.push({ dayIndex, dist });
            mealTasks.push(() => {
              logger.info(`Generating Day ${dayIndex + 1} ${dist.mealType}...`);
              return generateMeal({
                mealType: dist.mealType,
                calories: dist.calories,
                protein: dist.protein,
                carbs: dist.carbs,
                fat: dist.fat,
                // Use the effective goal (after purpose override), not the stored profile goal,
                // so the AI prompt matches the macros it's being asked to hit.
                goal: nutritionPlan.goal,
                dietPreference: healthProfile.dietPreference,
                cuisinePreference: healthProfile.cuisinePreference,
                diseases,
                forbiddenIngredients,
                limitedIngredients,
                preferredIngredients,
                retrievedContext: ragContextByMealType[dist.mealType] ?? null
              }, callBudget);
            });
          }
        }

        // Run meal generation with concurrency limit
        const mealResults = await runWithConcurrency(mealTasks, CONCURRENCY_LIMIT);

        // Step 6: Post-AI safety validation per meal (with per-meal retries)
        const validatedMeals = [];
        let safetyFailed = false;

        for (let i = 0; i < mealResults.length; i++) {
          let mealContent = mealResults[i];
          const dist = mealMeta[i].dist;
          const dayIndex = mealMeta[i].dayIndex;

          if (hasDiseases) {
            let mealSafe = false;
            for (let regenAttempt = 0; regenAttempt <= MAX_MEAL_REGEN_ATTEMPTS; regenAttempt++) {
              const result = validateGeneratedMeal(mealContent, diseases);
              if (result.safe) {
                mealSafe = true;
                break;
              }

              logger.warn(
                `Day ${dayIndex + 1} ${dist.mealType} safety check failed (attempt ${regenAttempt + 1}):`,
                result.reasons
              );

              // Regenerate this specific meal if budget allows
              if (regenAttempt < MAX_MEAL_REGEN_ATTEMPTS && callBudget.remaining > 0) {
                try {
                  mealContent = await generateMeal({
                    mealType: dist.mealType,
                    calories: dist.calories,
                    protein: dist.protein,
                    carbs: dist.carbs,
                    fat: dist.fat,
                    goal: nutritionPlan.goal,
                    dietPreference: healthProfile.dietPreference,
                    cuisinePreference: healthProfile.cuisinePreference,
                    diseases,
                    forbiddenIngredients,
                    limitedIngredients,
                    preferredIngredients,
                    errorFeedback: `Unsafe ingredients detected: ${result.reasons.join('; ')}`
                  }, callBudget);
                } catch (regenErr) {
                  logger.error(`Meal regeneration failed:`, regenErr.message);
                  break;
                }
              }
            }

            if (!mealSafe) {
              safetyFailed = true;
              lastErrors = ['Unable to generate safe meal plan for selected health conditions'];
              break;
            }
          }

          validatedMeals.push(mealContent);
        }

        if (safetyFailed) continue;

        // Assemble template from validated results
        const templateDayObjs = [];

        for (let dayIndex = 0; dayIndex < templateDays; dayIndex++) {
          const dayMeals = [];
          for (let mealIdx = 0; mealIdx < mealsPerDay; mealIdx++) {
            const resultIndex = dayIndex * mealsPerDay + mealIdx;
            const mealContent = validatedMeals[resultIndex];
            const dist = mealMeta[resultIndex].dist;

            dayMeals.push({
              mealType: dist.mealType,
              name: mealContent.name,
              description: mealContent.description,
              ingredients: mealContent.ingredients,
              benefits: mealContent.benefits,
              calories: dist.calories,
              macros: {
                protein: dist.protein,
                carbs: dist.carbs,
                fat: dist.fat
              }
            });
          }

          templateDayObjs.push({
            day: dayIndex + 1,
            title: `Day ${dayIndex + 1}`,
            theme: '',
            totalCalories: nutritionPlan.calorieTarget,
            macros: { ...nutritionPlan.macros },
            meals: dayMeals,
            tips: []
          });
        }

        // Validate the template (schema + logical)
        const templatePlan = {
          title: templateDays === 1 ? '1-Day Meal Plan' : `${templateDays}-Day Meal Plan`,
          days: templateDayObjs
        };

        const schemaResult = validateMealPlan(templatePlan);
        if (!schemaResult.valid) {
          logger.error(`Attempt ${attempt + 1}: Schema validation failed -`, schemaResult.errors);
          lastErrors = schemaResult.errors;
          continue;
        }

        const logicResult = validateFullMealPlan(templatePlan, healthProfile);
        if (!logicResult.valid) {
          logger.error(`Attempt ${attempt + 1}: Logical validation failed -`, logicResult.errors);
          lastErrors = logicResult.errors;
          continue;
        }

        // Template validated — replicate across weeks. For daily_health_based
        // (templateDays=1) we always cover a single day, so this collapses to
        // a copy of the single template day.
        const totalDays = templateDays === DAILY_TEMPLATE_DAYS
          ? 1
          : duration.weeks * templateDays;
        const allDays = [];
        for (let i = 0; i < totalDays; i++) {
          const templateDay = templateDayObjs[i % templateDays];
          const globalDay = i + 1;
          allDays.push({
            ...templateDay,
            day: globalDay,
            title: `Day ${globalDay}`,
            macros: { ...templateDay.macros },
            meals: templateDay.meals.map(m => ({
              ...m,
              macros: { ...m.macros },
              ingredients: [...m.ingredients],
              benefits: [...m.benefits]
            })),
            tips: [...templateDay.tips]
          });
        }

        const planTitle = templateDays === DAILY_TEMPLATE_DAYS
          ? 'Daily Meal Plan'
          : duration.weeks === 1
            ? '7-Day Meal Plan'
            : `${duration.weeks}-Week Meal Plan`;

        assembledPlan = {
          title: planTitle,
          days: allDays
        };
        break;
      } catch (genError) {
        logger.error(`Attempt ${attempt + 1}: Meal generation failed -`, genError.message);
        lastErrors = [genError.message];
      }
    }

    if (!assembledPlan) {
      logger.error('All retries exhausted. Last errors:', lastErrors);

      const isSafetyFailure = lastErrors?.some(e =>
        e.includes('Unable to generate safe meal plan')
      );
      const isFeasibilityFailure = lastErrors?.some(e =>
        e.includes('infeasible macro distribution')
      );

      return res.status(500).json({
        message: isFeasibilityFailure
          ? lastErrors[0]
          : isSafetyFailure
            ? 'Unable to generate safe meal plan for selected health conditions'
            : 'Meal content generation failed',
        reason: isFeasibilityFailure
          ? 'infeasible disease combination'
          : isSafetyFailure
            ? 'disease safety validation failed'
            : 'AI creative generation invalid',
        errors: lastErrors
      });
    }

    // Save meal plan to database. For daily_health_based the persisted duration
    // is a single day, regardless of what calculatePlanDuration returned.
    const persistedDuration = templateDays === DAILY_TEMPLATE_DAYS
      ? { weeks: 0, totalDays: 1 }
      : { weeks: duration.weeks, totalDays: duration.totalDays };

    const mealPlan = await MealPlan.create({
      userId,
      healthProfileId: healthProfile._id,
      title: assembledPlan.title,
      days: assembledPlan.days,
      duration: persistedDuration,
      purpose,
      aiModel: 'lm-studio',
      prompt: 'per-meal-generation',
      rawAiResponse: null
    });

    const response = {
      ok: true,
      message: 'Meal plan generated successfully',
      mealPlan
    };

    // Add medical disclaimer when diseases are present
    if (hasDiseases) {
      response.disclaimer = MEDICAL_DISCLAIMER;
    }

    // Surface unsupported diseases so the client knows which conditions were not handled
    if (unsupportedDiseases && unsupportedDiseases.length > 0) {
      response.unsupportedDiseases = unsupportedDiseases;
    }

    return res.status(201).json(response);
  } catch (error) {
    logger.error('Generate meal plan error:', error);
    return res.status(500).json({
      message: 'Failed to generate meal plan',
      error: error.message
    });
  }
}

// Get existing meal plan for user
export async function getMealPlan(req, res) {
  try {
    const userId = req.user?.id;
    if (!userId) return res.status(401).json({ message: 'Unauthorized' });

    const mealPlan = await MealPlan.findOne({ userId })
      .sort({ createdAt: -1 })
      .populate('healthProfileId');

    if (!mealPlan) {
      return res.status(404).json({ message: 'Meal plan not found' });
    }

    return res.json(mealPlan);
  } catch (error) {
    logger.error('Get meal plan error:', error);
    return res.status(500).json({ message: error.message });
  }
}

// Get all meal plans for user (pagination optional)
export async function getMealPlans(req, res) {
  try {
    const userId = req.user?.id;
    if (!userId) return res.status(401).json({ message: 'Unauthorized' });

    const limit = parseInt(req.query.limit) || 10;
    const skip = parseInt(req.query.skip) || 0;

    const mealPlans = await MealPlan.find({ userId })
      .sort({ createdAt: -1 })
      .limit(limit)
      .skip(skip)
      .populate('healthProfileId');

    const total = await MealPlan.countDocuments({ userId });

    return res.json({
      mealPlans,
      total,
      limit,
      skip
    });
  } catch (error) {
    logger.error('Get meal plans error:', error);
    return res.status(500).json({ message: error.message });
  }
}

// Delete meal plan
export async function deleteMealPlan(req, res) {
  try {
    const userId = req.user?.id;
    if (!userId) return res.status(401).json({ message: 'Unauthorized' });

    const { id } = req.params;
    const mealPlan = await MealPlan.findOne({ _id: id, userId });

    if (!mealPlan) {
      return res.status(404).json({ message: 'Meal plan not found' });
    }

    await MealPlan.deleteOne({ _id: id });
    return res.json({ ok: true });
  } catch (error) {
    logger.error('Delete meal plan error:', error);
    return res.status(500).json({ message: error.message });
  }
}

